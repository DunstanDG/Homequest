/**
 * Release notes, by day. Several deploys on the same day just add notes under that day's date: people see "what's
 * new" a day at a time (in detail) plus a one-line-per-area summary of the rest of the week, never one popup per
 * deploy.
 *
 * Writing a note:
 *   - `id`      unique and permanent (it's how "seen" is remembered): `<date>-<short-slug>`.
 *   - `date`    the day it shipped (YYYY-MM-DD). Newest first in the list.
 *   - `audience` 'all', 'parent' or 'child': children never see parent-only notes and vice versa.
 *   - `needs`   only for families that have one: 'care' (a baby or pet), 'baby', 'children', 'school'.
 *   - `title`   one short line, the detail view's heading. `short` is the 2-4 word label used in the week summary.
 *   - `body`    one or two sentences, plain English, what you can now do.
 *   - `to`      optional "Show me" link (an app route, e.g. '/calendar?v=plans').
 *   - `fix`     small fixes: bundled as "Plus N fixes" rather than listed one by one.
 * Never put real names of family, friends or schools here: this file is public.
 */

